/**
 * Look up CCF rank for a venue name.
 * Strategy: exact match (case-insensitive), then word-boundary substring match.
 */
export function lookupCcfRank(venue: string | null | undefined): string | null {
  if (!venue) return null
  const upper = venue.trim().toUpperCase()
  if (!upper) return null

  // 1. Exact match
  if (VENUE_RANK[upper]) return VENUE_RANK[upper]

  // 2. Word-boundary substring match
  const keys = Object.keys(VENUE_RANK).sort((a, b) => b.length - a.length)
  for (const key of keys) {
    if (key.length < 3) continue
    const shorter = Math.min(key.length, upper.length)
    const longer = Math.max(key.length, upper.length)
    if (key.length >= 10 && shorter < longer * 0.3) continue
    const escaped = key.replace(/[.*+?${}()|[\]\\]/g, '\\$&')
    const re = new RegExp(`(?<![A-Z0-9])${escaped}(?![A-Z0-9])`)
    if (re.test(upper)) return VENUE_RANK[key]
  }

  return null
}
